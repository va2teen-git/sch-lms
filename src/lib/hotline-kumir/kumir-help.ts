const TOPIC_SECTION_MAP: Record<string, string> = {
  команды: 'movement',
  движение: 'movement',
  предметы: 'interact',
  интерьер: 'interact',
  стелс: 'stealth',
  бой: 'stealth',
  датчики: 'sensors',
  условия: 'sensors',
  циклы: 'control',
  ветвление: 'control',
  алгоритмы: 'control',
};

export function resolveHelpSectionId(topic?: string): string | null {
  if (!topic) return null;
  const norm = topic.trim().toLowerCase().replace(/ё/g, 'е');
  return TOPIC_SECTION_MAP[norm] ?? null;
}
